use std::sync::Arc;

use crate::{Order, Retain, Rms, num_complex::Complex};
use sal_core::dbg::Dbg;
use serde::{Deserialize, Serialize};
use crate::{AtomicF64, OrderZone, ShortSigma, me};

/// Структура, для долгосрочного сохранения состояния на диск.
/// Содержит все переменные, необходимые для бесшовного восстановления фильтра Калмана
/// после перезапуска системы без потери накопленной истории износа.
#[derive(Clone, Copy, Debug, Serialize, Deserialize)]
pub struct Retained {
    /// Чистая (отфильтрованная) оценка энергии диагностической зоны на текущий момент.
    pub x_hat: f64,
    /// Внутренняя ошибка/неопределенность фильтра (ковариация ошибки оценки).
    pub p: f64,
    /// Unix-timestamp момента последнего сохранения (для ведения долгосрочных трендов).
    pub ts: u64,
}
impl Retained {
    /// Создает `Retained` с текущей меткой времени
    /// - `x_hat` - Чистая (отфильтрованная) оценка энергии диагностической зоны на текущий момент.
    /// - `p` - Внутренняя ошибка/неопределенность фильтра (ковариация ошибки оценки).
    pub fn new(x_hat: f64, p: f64) -> Self {
        let ts = chrono::Utc::now().timestamp().max(0) as u64;
        Self { x_hat, p, ts }
    }
}
impl Default for Retained {
    /// Создает `Retained` с текущей меткой времени
    fn default() -> Self {
        let ts = chrono::Utc::now().timestamp().max(0) as u64;
        Self { x_hat: f64::NAN, p: f64::NAN, ts }
    }
}

/// ### Адаптивный фильтр Калмана долгосрочной памяти
///
/// #### Назначение
/// Отслеживает истинное техническое состояние оборудования (дефекты, развивающиеся днями,
/// неделями и месяцами), полностью игнорируя кратковременные динамические всплески при
/// пусках, остановах и технологических флуктуациях нагрузки.
///
/// #### Инженерный принцип адаптации
/// Фильтр Калмана непрерывно балансирует между двумя силами: неопределенностью своей
/// математической модели старения (параметр Q) и неопределенностью текущего измерения
/// (динамическая сигма из Контура 1).
///
/// * **При пуске/резонансе**: Контур 1 выдает гигантскую краткосрочную дисперсию. Фильтр
///   видит, что датчик «в панике», вычисляет коэффициент Калмана K_t ≈ 0, полностью закрывает
///   «ворота» для новых данных и выдает значение, основанное исключительно на своей истории.
/// * **При плавном износе**: Сигнал растет медленно, Контур 1 фиксирует низкую дисперсию
///   (сигнал чистый). Фильтр открывает коэффициент K_t и плавно подтягивает долгосрочный
///   тренд вслед за реальной деградацией подшипника/муфты.
pub struct KalmanFilter {
    /// Идентификатор зоны диагностики (например, "order 1x_rpm", "0.5x_rpm").
    order_id: String,
    /// Скорость естественного старения оборудования (дисперсия процесса Q).
    /// Задает физический предел того, насколько износ может развиться за один шаг.
    /// Поскольку дефекты растут неделями, этот параметр должен быть микроскопическим.
    /// Рекомендуемый диапазон: от 1e-6 до 1e-8. Меньше значение — жестче фильтрация пусков.
    q: f64,
    /// Порог чувствительности для дельта-сохранения на диск (в долях/процентах).
    /// Значение 0.01 означает, что стейт будет отправлен на запись в канал только в случае,
    /// если отфильтрованное значение изменилось более чем на 1% от последнего сохраненного.
    /// Защищает Flash-память от преждевременного износа.
    saving_threshold: f64,
    // Переменные состояния фильтра (Стейт)
    x_hat: AtomicF64,
    /// Внутренняя ошибка/неопределенность фильтра (ковариация ошибки оценки).
    p: AtomicF64,
    // Внутренний трекер для контроля дельта-записи
    last_saved_x_hat: AtomicF64,
    // Канал отправки обновлений в поток долгосрочной записи
    retain: Arc<Retain>,
    // Входное значение (чистое или интегрированное по некоторой ширине полосы)
    value: OrderZone,
    /// Текущая краткосрочная дисперсия
    sigma: ShortSigma,
    dbg: Dbg,
}
//
impl KalmanFilter {
    /// Создает экземпляр фильтра Калмана.
    /// - `parent` - Идентификатор родительской сущности (для отладки).
    /// - `id` — имя зоны имя зоны порядка (например, 1.0x, 3.0x, BFSI...) в том числе для макировки в retain файле.
    /// - `q` — скорость старения процесса (рекомендуется 1e-7).
    /// - `saving_threshold` — порог изменения тренда для триггера записи на диск (например, 0.01 для 1%).
    /// - `retained` — ранее сохраненное состояние с диска (при первом запуске передать начальные базовые значения).
    /// - `retain` — канал отправки данных на диск.
    /// - `value` — Входное значение (чистое или интегрированное по некоторой ширине полосы)
    /// - `sigma` — Текущая краткосрочная дисперсия
    pub fn new(
        parent: impl Into<String>,
        id: String,
        q: f64,
        saving_threshold: f64,
        retained: Retained,
        retain: Arc<Retain>,
        value: OrderZone,
        sigma: ShortSigma,
    ) -> Self {
        let dbg = Dbg::new(parent, format!("{}({})", me::<Self>(), id));
        Self {
            order_id: id,
            q,
            saving_threshold,
            x_hat: AtomicF64::new(retained.x_hat),
            p: AtomicF64::new(retained.p),  // на старте должно быть NAN, тогда начальным значением будет первая RMS
            last_saved_x_hat: AtomicF64::new(retained.x_hat),
            retain,
            value,
            sigma,
            dbg,
        }
    }
    /// Возвращает индекс целевого порядка (например, 1.0x => 128, 3.0x => 256, BFSI => 1204...)
    pub fn order_index(&self) -> usize {
        self.value.target_index()
    }
    /// Возвращает целевого порядка (например, 1.0x => 1.0, 3.0x => 3.0...)
    pub fn target_order(&self) -> Order {
        self.value.target_order()
    }
    /// Возвращает имя целевого порядка (например, 1.0x, 3.0x, BFSI...)
    pub fn order_id(&self) -> &str {
        &self.order_id
    }
    /// Основной шаг фильтрации.
    /// - `orders` - массив результатов FFT
    ///
    /// Возвращает `Some(f64)` с новым чистым значением тренда, если произошло значимое изменение,
    /// требующее обновления графиков/логики дефектов. Возвращает `None`, если тренд стабилен.
    #[inline]
    pub fn eval(&self, orders: &[Complex<f32>]) -> Option<Rms<f64>> {
        let x = self.value.integrate(orders).value();
        // Текущая краткосрочная дисперсия возведенная в квадрат.
        let sigma = self.sigma.eval(x);
        let old_x_hat = self.x_hat.load();
        let pred_x_hat = if old_x_hat.is_finite() { old_x_hat } else { x };
        let old_p = self.p.load();
        let old_p = if old_p.is_finite() { old_p } else { sigma.powi(2) };
        // 1. ЭТАП ПРОГНОЗА (моделирование шага времени)
        // Предполагаем, что износ равен предыдущему, но неопределенность модели (p)
        // возрастает на величину скорости старения q.
        let pred_p = old_p + self.q;
        // 2. РАСЧЕТ КОЭФФИЦИЕНТА КАЛМАНА (Динамический вес доверия)
        // В знаменателе складываются неопределенность модели и текущий шум (дисперсия) из Контура 1.
        // При пуске sigma_short_sq стремится к бесконечности => gain стремится к 0.
        let gain = pred_p / (pred_p + sigma.powi(2));
        // 3. ЭТАП ОБНОВЛЕНИЯ (Коррекция прогноза новыми данными с учетом веса)
        let new_x_hat = pred_x_hat + gain * (x - pred_x_hat);
        let new_p = (1.0 - gain) * pred_p;
        // Сохраняем обновленный стейт обратно в атомики для следующих шагов
        self.x_hat.store(new_x_hat);
        self.p.store(new_p);
        // 4. ОПТИМИЗАЦИЯ ЗАПИСИ НА ДИСК (Дельта-фильтрация IO-операций)
        let last_saved = self.last_saved_x_hat.load();
        let last_saved = if !last_saved.is_finite() {
            self.last_saved_x_hat.store(new_x_hat);
            let _ = self.retain.store(&self.order_id, Retained::new(new_x_hat, new_p));
            new_x_hat
        } else {
            last_saved
        };
        // Находим абсолютное значение для масштабирования
        let abs_val = new_x_hat.abs().max(last_saved.abs());
        // Вычисляем модуль относительного изменения тренда
        let relative_change = if abs_val == 0.0 {
            0.0
        } else {
            (new_x_hat - last_saved).abs() / abs_val
        };
        // Если тренд сдвинулся сильнее порога (например, более чем на 1%),
        // отправляем стейт в канал для фоновой записи на диск
        if relative_change >= self.saving_threshold {
            self.last_saved_x_hat.store(new_x_hat);
            // Текущее системное время в секундах
            // Отправляем в канал без блокировки текущего потока обработки спектра.
            // Если принимающая сторона диска занята, данные встанут в очередь.
            let _ = self.retain.store(&self.order_id, Retained::new(new_x_hat, new_p));
            log::debug!("{}.eval | Order {}, {new_x_hat}", self.dbg, self.order_id);
            // Возвращаем новое значение, так как тренд совершил значимое изменение
            Some(Rms(new_x_hat))
        } else {
            // Изменение слишком незначительно, логике верхнего уровня и диску сообщать не нужно
            None
        }
    }
}
