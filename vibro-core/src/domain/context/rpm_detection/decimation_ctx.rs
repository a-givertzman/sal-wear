use std::collections::VecDeque;
/// Коэффициенты КИХ-фильтра нижних частот (ФНЧ) для антиалиасинга.
/// 
/// Рассчитаны методом оконного синтеза для следующих параметров:
/// * Частота дискретизации (`Fs`): 320 кГц
/// * Частота среза (`Fc`): 8 кГц (обеспечивает подавление до частоты Найквиста прореженного сигнала — 16 кГц)
/// * Количество отсчетов (тапов): 32
/// * Сглаживающее окно: Хемминга
pub const FIR_TAPS_M20_N32: [f64; 32] = [
    -0.000713, -0.001646, -0.002497, -0.002570, -0.000958,  0.003180,  0.010260,  0.020141,
     0.032213,  0.045431,  0.058371,  0.069485,  0.077366,  0.081125,  0.081125,  0.077366,
     0.069485,  0.058371,  0.045431,  0.032213,  0.020141,  0.010260,  0.003180, -0.000958,
    -0.002570, -0.002497, -0.001646, -0.000713,  0.000000,  0.000000,  0.000000,  0.000000,
];
///
/// Результат работы дециматора, объединяющего антиалиасинг-фильтрацию (КИХ) и прореживание сигнала.
/// 
/// Структура инкапсулирует параметры дискретизации, текущий выходной буфер, а также 
/// внутреннее состояние фильтра и счетчик фазы для бесшовной потоковой обработки чанков.
pub struct DecimationCtx {
    /// Частота дискретизации сигнала после децимации, Гц (`sample_rate / factor`).
    /// 
    /// Для базовой конфигурации (320 кГц / 20) составляет 16 000 Гц (16 кГц).
    pub f_sample_dec: f64,
    /// Коэффициент прореживания `M`. Означает, что КИХ-фильтр вычисляется для каждого входного отсчета, 
    /// но на выход выдается только один отсчет из каждых `M` входных.
    pub factor: usize,
    /// Выходной буфер для децимированного сигнала текущего чанка.
    /// 
    /// Вектор полностью очищается на каждом цикле обработки (`eval`) и не сохраняет историю между чанками.
    /// Например, для чанка в 512 отсчетов и `M = 20` буфер будет содержать 25 или 26 отсчетов. 
    /// Сигнал в буфере уже очищен от постоянной составляющей (DC).
    pub decimated: Vec<f64>,
    /// Линия задержки (состояние) КИХ-фильтра, реализующая сдвиговый регистр.
    /// 
    /// Хранит последние `N` отсчетов входного сигнала (где `N` — количество тапов фильтра). 
    /// Новейшие отсчеты располагаются в начале (индекс 0). Состояние сохраняется между чанками.
    pub dec_fir_state: VecDeque<f64>,
    /// Фазовый счетчик прореживания, принимающий значения в диапазоне `0..factor`.
    /// 
    /// Переходит между чанками данных. Поскольку размер входящего чанка (например, 512) может быть 
    /// не кратен коэффициенту децимации (например, 20), этот счетчик отслеживает истинную фазу 
    /// взятия отсчетов, исключая фазовые искажения и пропуски на стыках пакетов.
    pub dec_counter: usize,
}

impl DecimationCtx {
    /// Создает и инициализирует контекст дециматора с точным выделением памяти под внутренние структуры.
    ///
    /// # Аргументы
    /// * `sample_rate` - Исходная частота дискретизации входного сигнала (например, 320000.0 Гц).
    /// * `samples_capacity` - Ожидаемый размер входного чанка в отсчетах (используется для предрасчета размера `decimated`).
    /// * `factor` - Коэффициент прореживания `M`.
    pub fn new(
        sample_rate: f64,
        samples_capacity: usize, 
        factor: usize
    ) -> Self {
        // Вычисляем максимальный возможный размер выходного буфера (+1 на случай дробного сдвига фазы)
        let expected_capacity = samples_capacity / factor + 1;
        Self { 
            f_sample_dec: sample_rate / (factor as f64), 
            // Предвыделение памяти для исключения реаллокаций во время заполнения буфера децимированных данных
            decimated: Vec::with_capacity(expected_capacity), 
            // Инициализируем сдвиговый регистр КИХ-фильтра нулями под размер массива коэффициентов
            dec_fir_state: VecDeque::from(vec![0.0; FIR_TAPS_M20_N32.len()]), 
            dec_counter: 0,
            factor,
        }
    }
}

impl Default for DecimationCtx {
    /// Создает пустой контекст дециматора со значениями по умолчанию.
    /// 
    /// Линия задержки фильтра и выходной буфер инициализируются без аллокации памяти, 
    /// а коэффициенты и частоты сбрасываются в `0`. Рекомендуется использовать `new` для штатной работы.
    fn default() -> Self {
        Self {
            f_sample_dec: 0.0,
            factor: 0,
            decimated: Vec::new(),
            // По умолчанию очередь пуста; при потоковой обработке она заполнится динамически,
            // однако для DSP-алгоритмов предпочтительнее предзаполнение нулями через конструктор `new`
            dec_fir_state: VecDeque::new(),
            dec_counter: 0,
        }
    }
}
