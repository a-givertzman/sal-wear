use rustfft::num_complex::Complex;
use crate::{Biquad, FSampleDec};
/// Добротность (Q) первого биквадратного звена для каскадного ФНЧ Баттерворта 4-го порядка.
const Q_FACTOR_1: f64 = 0.5412;
/// Добротность (Q) второго биквадратного звена для каскадного ФНЧ Баттерворта 4-го порядка.
/// 
/// Сочетание парных добротностей Q1 и Q2 формирует классический гладкий 
/// аналоговый прототип Баттерворта 4-го порядка с максимально плоской 
/// амплитудно-частотной характеристикой (АЧХ) в полосе пропускания.
const Q_FACTOR_2: f64 = 1.3066;
/// Контекст и состояние фиксированного ФНЧ полосы слежения.
///
/// Структура инкапсулирует два последовательно соединенных звена второго порядка 
/// (Биквада), образующих ИИХ-фильтр (IIR) 4-го порядка, а также буферы выходного сигнала. 
/// Хранение линий задержки биквадов внутри контекста обеспечивает непрерывность 
/// фильтрации комплексного сигнала между последовательными чанками данных.
pub struct LPFTrackingBandCtx {
    /// Первая стадия каскадной фильтрации (Биквадратное звено 1)
    pub stage1: Biquad,
    /// Вторая стадия каскадной фильтрации (Биквадратное звено 2)
    pub stage2: Biquad,
    /// Отфильтрованная комплексная огибающая `I[n] + j*Q[n]` компоненты 1X.
    /// 
    /// Буфер полностью очищается на каждом цикле обработки (`eval`) и не накапливает 
    /// историю отсчетов между чанками данных.
    pub filtered_signal: Vec<Complex<f64>>,
    /// Амплитуда огибающей `A[n] = sqrt(I² + Q²)` для детектора валидности.
    /// Параллельна `filtered_signal`, очищается на каждом `eval`.
    pub amplitude: Vec<f64>,
}
//
impl LPFTrackingBandCtx {
    /// Создает и инициализирует контекст ФНЧ с точным расчетом коэффициентов биквадов 
    /// и предварительным резервированием памяти.
    ///
    /// Выделение емкости (`with_capacity`) для вектора отфильтрованного сигнала исключает 
    /// накладные расходы процессора на динамическую реаллокацию памяти (heap allocations) 
    /// во время работы высоконагруженного DSP-конвейера.
    ///
    /// # Аргументы
    /// * `f_sample_dec` - Частота дискретизации после децимации.
    /// * `chunk_size_dec` - Ожидаемое число отсчётов децимированного сигнала в одном пакете.
    /// * `f_cutoff` - Частота среза одного ФНЧ, Гц. Равна `B/2`, где `B` — полная полоса слежения,
    ///   вычисляемая в конфиге по формуле раздела 4, п. 2 (`RpmDetectionConf::tracking_cutoff_hz`).
    ///
    /// # Panics
    /// Если `f_cutoff` не лежит в `(0, f_sample_dec / 10)`: иначе фильтр численно неустойчив
    /// или не имеет смысла (опечатка в конфиге).
    pub fn new(
        f_sample_dec: FSampleDec<f64>, 
        chunk_size_dec: usize,
        f_cutoff: f64,
    ) -> Self {
        assert!(
            f_cutoff > 0.0 && f_cutoff < f_sample_dec.value() / 10.0,
            "LPFTrackingBandCtx::new | f_cutoff = {f_cutoff} Гц вне допустимого диапазона для f_sample_dec = {} Гц",
            f_sample_dec.value()
        );
        Self { 
            stage1: Biquad::new(f_cutoff, f_sample_dec.value(), Q_FACTOR_1), 
            stage2: Biquad::new(f_cutoff, f_sample_dec.value(), Q_FACTOR_2), 
            filtered_signal: Vec::with_capacity(chunk_size_dec),
            amplitude: Vec::with_capacity(chunk_size_dec),
        }
    }
}
//
impl Default for LPFTrackingBandCtx {
    /// Создает пустой контекст ФНЧ полосы слежения со значениями по умолчанию.
    /// 
    /// Векторы инициализируются без аллокации памяти на куче, а звенья биквадов 
    /// сбрасываются в нулевые коэффициенты. Для штатной работы в DSP-цепочках 
    /// настоятельно рекомендуется использовать метод `new` для корректного расчета коэффициентов.
    fn default() -> Self {
        Self {
            stage1: Default::default(),
            stage2: Default::default(),
            filtered_signal: Default::default(),
            amplitude: Default::default(),
        }
    }
}
