/// Перечисление глобальных состояний конвейера трекинга и валидации фазы вала.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TrackState {
    /// Сигнал стабилен, амплитуда огибающей находится в пределах нормы над порогом гистерезиса. 
    /// Вычисленная фаза абсолютно валидна и готова для ордерного анализа.
    Valid,
    /// Зафиксировано падение амплитуды сигнала ниже допустимого порога, однако длительность 
    /// этого сбоя всё еще короче времени установления фильтра (tau_settle). 
    /// Фаза временно считается невалидной, но система ожидает окончания переходного процесса.
    Degraded,
    /// Длительность просадки сигнала превысила критический порог (дольше tau_settle). 
    /// Вычисляемая фаза считается полностью разрушенной, конвейер переходит в режим 
    /// принудительного повторного поиска и захвата частоты (например, через сетку Герцеля).
    Acquisition,
}
/// Контекст состояния детектора валидности амплитуды огибающей.
///
/// Хранит долгосрочное состояние конечного автомата валидации: флаг гистерезиса
/// `valid`, счётчик длительности невалидности `invalid_samples` и глобальный
/// статус `state`. Хранение состояния внутри контекста обеспечивает бесшовный
/// перенос счётчиков между последовательными чанками.
pub struct ValidityDetectorCtx {
    /// Текущий мгновенный статус валидности полезного сигнала, рассчитанный с учетом гистерезиса.
    pub valid: bool,
    /// Счетчик отсчетов, фиксирующий непрерывную длительность текущего аварийного состояния. 
    /// Обнуляется, пока `valid == true`; накапливается на каждом невалидном отсчёте.
    pub invalid_samples: usize,
    /// Текущее глобальное состояние тракта слежения за фазой вала.
    pub state: TrackState,
}
//
impl ValidityDetectorCtx {
    /// Создает и инициализирует контекст детектора валидности.
    ///
    /// Конвейер стартует из безопасного дефолтного режима поиска частоты
    /// `TrackState::Acquisition`.
    pub fn new() -> Self {
        Self { 
            valid: false, 
            invalid_samples: 0, 
            state: TrackState::Acquisition, 
        }
    }
}
//
impl Default for ValidityDetectorCtx {
    /// Создает контекст детектора валидности со значениями по умолчанию:
    /// `valid = false`, `invalid_samples = 0`, `state = TrackState::Acquisition`.
    fn default() -> Self {
        Self { 
            valid: false, 
            invalid_samples: 0, 
            state: TrackState::Acquisition, 
        }
    }
}
