/// Перечисление глобальных состояний конвейера трекинга и валидации фазы вала.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TrackState {
    /// Сигнал стабилен, амплитуда огибающей находится в пределах нормы над порогом гистерезиса. 
    /// Вычисленная фаза абсолютно валидна и готова для ордерного анализа.
    Valid,
    /// Зафиксировано падение амплитуды сигнала ниже допустимого порога, однако длительность 
    /// этого сбоя всё еще короче времени установления фильтра (tau_settle). 
    /// Фаза временно считается невалидной, но система ожидает окончания переходного процесса.
    Degraded,
    /// Длительность просадки сигнала превысила критический порог (дольше tau_settle). 
    /// Вычисляемая фаза считается полностью разрушенной, конвейер переходит в режим 
    /// принудительного повторного поиска и захвата частоты (например, через сетку Герцеля).
    Acquisition,
}
/// Контекст и буферы состояния детектора валидности амплитуды огибающей.
///
/// Структура хранит долгосрочные параметры конечного автомата валидации и текущие 
/// выходные буферы флагов для обрабатываемого пакета данных. Хранение состояния 
/// внутри контекста обеспечивает бесшовный перенос счетчиков между последовательными чанками.
pub struct ValidityDetectorCtx {
    /// Текущий мгновенный статус валидности полезного сигнала, рассчитанный с учетом гистерезиса.
    pub valid: bool,
    /// Счетчик отсчетов, фиксирующий непрерывную длительность текущего аварийного состояния. 
    /// Сбрасывается в 0 при каждом прохождении верхнего порога гистерезиса.
    pub invalid_samples: usize,
    /// Текущее глобальное состояние тракта слежения за фазой вала.
    pub state: TrackState,
    /// Буфер флагов валидности, заполняемый поотсчетно для каждого сэмпла текущего пакета данных.
    /// 
    /// Вектор полностью очищается через clear() на каждом цикле вызова `eval` текущего чанка.
    pub valid_flags: Vec<bool>,
}
//
impl ValidityDetectorCtx {
    /// Создает и инициализирует контекст детектора валидности с предварительным резервированием памяти.
    ///
    /// Конвейер стартует из безопасного дефолтного режима поиска частоты `TrackState::Acquisition`. 
    /// Предвыделение емкости (`with_capacity`) для вектора флагов исключает накладные расходы процессора 
    /// на повторные аллокации памяти во время работы горячего DSP-цикла.
    ///
    /// # Аргументы
    /// * `signal_capacity` - Ожидаемый максимальный размер выходного чанка прореженного сигнала 
    ///   в отсчетах (используется для предрасчета размера буфера `valid_flags`).
    pub fn new(signal_capacity: usize) -> Self {
        Self { 
            valid: false, 
            invalid_samples: 0, 
            state: TrackState::Acquisition, 
            valid_flags: Vec::with_capacity(signal_capacity),
        }
    }
}
//
impl Default for ValidityDetectorCtx {
    /// Создает пустой контекст детектора валидности со значениями по умолчанию.
    /// 
    /// Вектор флагов инициализируется с нулевой емкостью без выделения памяти на куче. 
    /// Рекомендуется использовать конструктор `new` для исключения динамических реаллокаций памяти 
    /// на куче (heap allocations) во время высоконагруженной потоковой обработки чанков.
    fn default() -> Self {
        Self { 
            valid: false, 
            invalid_samples: 0, 
            state: TrackState::Acquisition, 
            valid_flags: Vec::new(),
        }
    }
}
