use rustfft::num_complex::Complex;
///
/// Результат работы комплексного гетеродина (сдвиг спектра компоненты 1X на нулевую частоту).
///
/// Контекст хранит состояние фазы гетеродина для обеспечения непрерывности интегрирования 
/// между обрабатываемыми чанками данных, а также буферы выходного комплексного сигнала.
pub struct ComplexLocalOscillatorCtx {
    /// Комплексный аналитический сигнал `y[n] = I[n] + j*Q[n]`.
    /// 
    /// Получается путем умножения входного вещественного сигнала на сопряженную комплексную экспоненту `e^(-j * phi)`.
    /// Полезная компонента первой оборотной гармоники (1X) в этом сигнале сдвигается на околонулевую частоту `delta ≈ 0`.
    pub complex_signal: Vec<Complex<f64>>,
    /// Массив значений накопленной фазы гетеродина `phi_het[n]` для каждого отсчета в рамках текущего чанка.
    /// 
    /// Используется для ведения истории изменения фазы, диагностики и последующих этапов демодуляции.
    pub phi_het: Vec<f64>,
    /// Конечное значение накопленной фазы гетеродина на последнем отсчете текущего чанка.
    /// 
    /// Является критически важным базовым состоянием. Переносится в качестве начального значения фазы 
    /// для следующего чанка данных, обеспечивая непрерывность интеграла скорости вала и исключая скачки фазы.
    pub phi_het_last: f64,
}
//
impl ComplexLocalOscillatorCtx {
    /// Создает новый контекст осциллятора с предварительным выделением памяти под размер обрабатываемого сигнала.
    ///
    /// Выделение емкости (capacity) предотвращает повторные аллокации буферов `Vec` внутри 
    /// высоконагруженного цикла гетеродинирования.
    ///
    /// # Аргументы
    /// * `chunk_size` - Размер входящего чанка данных в отсчетах (используется для расчета емкости буферов).
    pub fn new(chunk_size: usize) -> Self {
        Self { 
            complex_signal: Vec::with_capacity(chunk_size), 
            phi_het: Vec::with_capacity(chunk_size), 
            phi_het_last: 0.0, 
        }
    }
}
//
impl Default for ComplexLocalOscillatorCtx {
    /// Создает пустой контекст осциллятора со значениями по умолчанию.
    /// 
    /// Векторы инициализируются без выделения памяти на куче, начальное значение последней фазы устанавливается в `0.0`.
    fn default() -> Self {
        Self {
            complex_signal: Vec::new(),
            phi_het: Vec::new(),
            phi_het_last: 0.0,
        }
    }
}
