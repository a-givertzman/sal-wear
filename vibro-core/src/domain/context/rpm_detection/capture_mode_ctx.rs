/// Порог отношения сигнал/шум (SNR) для валидации пика алгоритма Герцеля.
///
/// Определяет минимально допустимую физическую амплитуду выделенной гармоники,
/// при которой пик считается истинным сигналом, а не флуктуацией белого шума в буфере.
/// Если `max_amp` ниже этого значения, захват частоты отклоняется.
pub const NOIZE_THRESHOLD: f64 = 5.0;
/// Контекст и состояние алгоритма в режиме захвата (Capture Mode).
///
/// Данная структура хранит конфигурационные параметры и текущие результаты сканирования
/// частотной сетки, когда система теряет синхронизацию фазы (например, при старте,
/// потере сигнала 1X или устаревании сетевых данных RPM).
///
/// Контекст используется для грубого поиска пика фильтрами Герцеля в окрестности f
/// и последующего точного восстановления фазы через параболическую интерполяцию.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct CaptureModeCtx {
    /// Точная вычисленная частота f_precise после параболической интерполяции.
    pub f_precise: f64,
    /// Полуширина окна поиска вокруг базовой частоты гетеродина f в Герцах.
    /// Определяет границы сканирования: f - delat_F, f + delta_F
    pub search_half_window_hz: f64,
    /// Количество шагов сканирования сетки Герцеля в одну сторону от центра.
    /// Общее число расчетных точек (бинов) на сетке равно `(search_steps * 2) + 1`.
    pub search_steps: usize,
    /// Флаг, указывающий, что в текущем цикле была успешно найдена и обновлена точная частота.
    pub is_updated: bool,
}
//
impl CaptureModeCtx {
    /// Создает новый контекст режима захвата с заданными параметрами частотной сетки.
    ///
    /// # Аргументы
    /// * `half_window` — Полуширина диапазона поиска в Гц ($\pm \Delta F$).
    /// * `steps` — Количество шагов сканирования в одну сторону (минумум 1).
    pub fn new(half_window: f64, steps: usize) -> Self {
        Self {
            f_precise: 0.0,
            search_half_window_hz: half_window.abs(),
            search_steps: steps.max(1),
            is_updated: false,
        }
    }
    ///
    /// Сбрасывает вычисленную частоту и флаги обновления в исходное состояние.
    /// Вызывается принудительно при полной потере сигнала или переинициализации трекера.
    pub fn reset(&mut self) {
        self.f_precise = 0.0;
        self.is_updated = false;
    }
    ///
    /// Вычисляет дискретное расстояние (разрешение) между соседними узлами сетки поиска ($\Delta f$).
    #[inline]
    pub fn resolution_step(&self) -> f64 {
        if self.search_steps > 0 {
            self.search_half_window_hz / (self.search_steps as f64)
        } else {
            0.0
        }
    }
}
//
impl Default for CaptureModeCtx {
    /// Инициализирует контекст со стабильными консервативными параметрами по умолчанию.
    /// 
    /// По умолчанию: f_precise = 0.0, окно поиска 2.0 Гц, 5 шагов в каждую сторону 
    /// (шаг сетки delta_f = 0.4 Гц, всего 11 расчетных точек).
    fn default() -> Self {
        Self {
            f_precise: 0.0,
            search_half_window_hz: 2.0,
            search_steps: 5,
            is_updated: false,
        }
    }
}
