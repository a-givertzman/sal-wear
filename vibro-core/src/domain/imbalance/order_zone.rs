///    * Ожидаемый результат: Проверяем корректность работы energy_correction_factor. Значение RMS на выходе должно строго соответствовать аналитическому RMS белого шума в этой полосе. Окно Ханна не должно занижать или завышать общую интегральную энергию полосы.
/// * Тест 1.3: Граничные порядки (0.5x и 3x RPM)
/// * Что делаем: Проверяем крайние диагностические зоны. Для субгармоники $0.5\times$ центр смещается близко к нулю спектра, а для $3\times$ уходит в область высоких порядков.
///    * Ожидаемый результат: Интегратор корректно рассчитывает индексы и веса как для низких, так и для высоких порядков.
/// 
/// ### 2. Спектральное тестирование OrderZone (White Box)
/// 
/// Цель: Верифицировать корректность работы с индексами массивов, защиту от утечки спектра (leakage) и пересечения частотных полос.
/// 
/// * 👉 Тест 2.1: Сдвиг пика внутри зоны (Защита от «дыхания» RPM)
/// * Что делаем: Подаем синусоиду с амплитудой $1.0\ g$, но смещаем её частоту на $+0.02$ порядка от центра гармоники (пик смещается на несколько бинов вбок, но остается внутри half_width).
///    * Ожидаемый результат: Выходное значение RMS остается стабильным (колебания тренда не превышают сотых долей процента). Это докажет, что окно Ханна успешно «склеивает» уплывающую энергию и гасит цифровой ступенчатый шум границ.
/// * 👉 Тест 2.2: Внеполосная помеха (Селективность фильтра)
/// * Что делаем: Помещаем гигантский пик вибрации ($10.0\ g$) строго за пределами зоны интегрирования (например, на расстоянии $+1.5 \cdot \text{half\_width}$ от центра). Внутри самой зоны — тишина.
///    * Ожидаемый результат: Интегратор должен вернуть значение, близкое к нулю. Тест подтверждает, что спад весов окна Ханна эффективно изолирует зону от соседних паразитных вибраций.
/// * Тест 2.3: Наложение зон (Ослабление люфтов против дисбаланса)
