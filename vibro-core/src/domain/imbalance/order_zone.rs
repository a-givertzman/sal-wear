/// 
/// * 👉 Тест 3.1: Защита от выхода за границы спектра (Краевые эффекты)
/// * Что делаем: Инициализируем зону для очень высокого порядка, где правая граница окна idx_end физически улетает за пределы Найквиста ($N_{fft} / 2$), или зону $0.5\times$ с широким окном, где левая граница idx_start уходит в отрицательные индексы.
///    * Ожидаемый результат: Код не паникует. Срабатывает внутренняя защита .max(0) и .min(n_fft / 2). Вектор весов генерируется корректно для усеченной зоны.
/// * 👉 Тест 3.2: Экстремально узкое окно (Зона из одного бина)
/// * Что делаем: Передаем в конфигурацию half_width = 0.0001 (меньше, чем разрешение $\Delta O$). В таком сценарии n_bins становится равным $1$.
///    * Ожидаемый результат: Внутреннее условие if n_bins > 1 корректно обрабатывает этот случай, присваивая весу значение 1.0. Защита от деления на ноль в energy_correction_factor отрабатывает штатно.
/// * Тест 3.3: Пустой или некорректный спектр
/// * Что делаем: Передаем в метод integrate массив orders, длина которого меньше, чем расчетный idx_start (например, пустой срез &[] или поврежденные данные).
///    * Ожидаемый результат: Безопасный пропуск циклов благодаря проверке if fft_idx < orders.len(). Метод возвращает Rms(0.0), падения программы не происходит.
/// * Тест 3.4: NaN и Infinity во входном потоке
/// * Что делаем: Заполняем один из бинов внутри зоны значением Complex::new(f64::NAN, f64::INFINITY).
///    * Ожидаемый результат: Безопасная обработка через .unwrap_or(0.0), подменяющая неопределенность нулем.
/// 
/// ### 4. Производительность OrderZone в Проде (Performance)
/// 
/// Цель: Оценить скорость работы алгоритма под реальной нагрузкой (микроклиматические бенчмарки через criterion).
/// 
/// * 👉 Тест 4.1: Потоковое вычисление пула зон (Пром-нагрузка)
/// * Что делаем: Создаем массив из 7 экземпляров OrderZone (все целевые гармоники: $0.5\times, 1.0\times, 1.5\times, 2.0\times, 2.5\times, 3.0\times, 3.5\times$). Запускаем метод integrate в цикле $10\ 000$ раз для буфера $N_{fft} = 8192$.
///    * Ожидаемый результат: Бенчмарк должен показать, что обработка всего пакета зон занимает микросекунды. Локальность данных (последовательный обход маленького участка памяти idx_start..idx_end) должна обеспечивать 100% попадание в L1-кэш процессора.
/// * Тест 4.2: Оценка стоимости Generics (f32 против f64)
/// * Что делаем: Сравниваем время выполнения метода integrate при подаче массива Complex<f32> и Complex<f64>.
///    * Ожидаемый результат: Верификация того, что компилятор успешно выполнил мономорфизацию обобщенного метода (#[inline]), и накладные расходы на приведение типов .to_f64() отсутствуют.
///
mod tests {
    use super::*;
    use rustfft::num_complex::Complex;

    #[test]
    fn test_perfect_sine_amplitude_recovery() {
        let n_fft = 8192;
        let n_rev = 64;
        let target_order = 1.0;
        let half_width = 0.05; // ±0.05 порядка
        
        let zone = OrderZone::new(target_order, half_width, n_fft, n_rev);
        
        // Создаем пустой спектр (размером N_fft / 2)
        let mut spectrum = vec![Complex::new(0.0, 0.0); n_fft / 2];
        
        // Центральный бин для порядка 1.0 при N_fft=8192 и N_rev=64 равен 128
        // Генерируем пик с чистой синусоидальной амплитудой 1.0 g
        // На входе FFT: A_raw = Физическая_Амплитуда * (N_fft / 2)
        spectrum[128] = Complex::new((n_fft / 2) as f64, 0.0);
        
        let rms_result = zone.integrate(&spectrum);
        
        // Ожидаем RMS значение синусоиды: 1.0 / sqrt(2) ≈ 0.70710678
        let expected_rms = 1.0 / 2.0.sqrt();
        
        // Проверяем точность до 6 знака после запятой
        assert!((rms_result.0 - expected_rms).abs() < 1e-6, 
                "Expected RMS {:.6}, got {:.6}", expected_rms, rms_result.0);
    }

}