use crate::{Rms, num_complex::{Complex, ComplexFloat}};

/// Интегрирует спектральную энергию для заданной зоны порядков.
/// Находит максимум энергии гармоники и интегрирует зону растекания (Leakage).
pub struct OrderZone {
    /// Коэффициент для восстановления среднеквадратичного значения амплитуды (RMS) из спектра FFT, `k = sqrt(2) / n_fft`.
    amplitude_factor: f64,
    /// Стартовый индекс бина в массиве FFT для сканирования зоны
    idx_start: usize,
    /// Конечный индекс бина в массиве FFT для сканирования зоны
    idx_end: usize,
    /// Количество бинов, которые надо интегрировать слева и справа от найденного пика
    leakage: usize,
}
//
impl OrderZone {
    /// Создает новый `OrderZone`.
    /// * `target_order` — целевой порядок гармоники (например, 1.0, 2.0, 0.5 RPM).
    /// * `half_width` — настраиваемая полуширина захвата в долях порядка (например, 0.05).
    ///     - Для жестких условий (стабильные обороты) берут ±0.02 порядка.
    ///     - Для плавающих режимов (пуски/выбеги) ширину увеличивают до ±0.05..±0.1 порядка.
    /// * `leakage` — сколько всего бинов интегрировать в зоне найденного пика (обычно 3..5).
    /// * `n_fft` — размер буфера FFT (например, 8192).
    /// * `n_rev` — количество отсчетов на один оборот вала.
    pub fn new(target_order: f64, half_width: f64, leakage: usize, n_fft: usize, n_rev: usize) -> Self {
        let delta_o = n_rev as f64 / n_fft as f64; // Разрешение спектра порядков [1, 2, 3]
        // Находим центральный бин и полуширину в бинах [1, 2, 3]
        let idx_center = (target_order / delta_o).round() as isize;
        let b_half = (half_width / delta_o).ceil() as isize;
        let isize_start = idx_center - b_half;
        let isize_end = idx_center + b_half;
        // Защита от выхода за границы спектра (от 0 до N_fft / 2)
        let idx_start = isize_start.max(0) as usize;
        let idx_end = isize_end.min((n_fft / 2) as isize) as usize;
        // Генерируем веса окна Ханна (полупериод косинуса / колокол) [1, 2]
        Self {
            amplitude_factor: 2.0.sqrt() / n_fft as f64,
            idx_start,
            idx_end,
            leakage: leakage / 2,
        }
    }
    /// Возвращает RMS энергию зоны.
    /// - `orders` - Массив комплексных амплитуд спектра FFT (размером N_fft / 2).
    #[inline]
    pub fn integrate<T>(&self, orders: &[Complex<T>]) -> crate::Rms<f64> 
    where 
        T: crate::num_traits::Float + crate::num_traits::FloatConst + crate::num_traits::ToPrimitive 
    {
        if orders.is_empty() || self.idx_start >= orders.len() {
            return crate::Rms(0.0);
        }
        // --- ШАГ 1: Поиск индекса максимальной амплитуды в зоне сканирования ---
        let max_idx;    // = self.idx_start;
        // let mut max_amp = -1.0;
        let end_limit = self.idx_end.min(orders.len() - 1);
        // for idx in self.idx_start..=end_limit {
        //     let amp = orders[idx].abs().to_f64().unwrap_or(0.0);
        //     if amp > max_amp {
        //         max_amp = amp;
        //         max_idx = idx;
        //     }
        // }
        if let Some((local_idx, _)) = orders[self.idx_start..=end_limit].iter().enumerate()
            .map(|(idx, val)| {
                let amp = val.abs().to_f64().unwrap_or(0.0);
                (idx, amp)
            })
            .max_by(|(_, amp_a), (_, amp_b)| amp_a.partial_cmp(amp_b).unwrap_or(std::cmp::Ordering::Equal))
        {
            // Если диапазон был не пустой, обновляем значения
            // max_amp = amp;
            max_idx = self.idx_start + local_idx;
        } else  {
            max_idx = self.idx_start + end_limit / 2;
        }
        // Интегрирование энергии (прямоугольное окно) вокруг пика ---
        // Определяем локальные границы вокруг найденного максимума
        let int_start = max_idx.saturating_sub(self.leakage).max(self.idx_start);
        let int_end = (max_idx + self.leakage).min(end_limit);
        let mut weighted_amplitude_sum = 0.0;
        for idx in int_start..=int_end {
            let raw_amplitude = orders[idx].abs().to_f64().unwrap_or(0.0);
            weighted_amplitude_sum += raw_amplitude.powi(2);
        }
        // Извлекаем корень и масштабируем коэффициент амплитуды в RMS
        Rms((weighted_amplitude_sum).sqrt() * self.amplitude_factor)
    }
}
