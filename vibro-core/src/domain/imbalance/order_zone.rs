use crate::{Rms, num_complex::{Complex, ComplexFloat}};

/// Интегрирует спектральную энергию для фиксированной зоны порядков.
/// Выделяет полосу бинов вокруг целевой гармоники и накладывает сглаживающее косинусное окно.
pub struct OrderZone {
    /// Коэффициент для восстановления среднеквадратичного значения амплитуды (RMS) из спектра FFT, `k = sqrt(2) / n_fft`.
    amplitude_factor: f64,
    /// Стартовый индекс бина в массиве FFT
    idx_start: usize,
    /// Количество бинов, входящих в зону интегрирования (N_bins)
    n_bins: usize,
    /// Заранее вычисленные веса окна Ханна для каждого бина в зоне
    window_weights: Vec<f64>,
    /// Коэффициент коррекции энергии окна (сумма квадратов весов)
    energy_correction_factor: f64,
}
//
impl OrderZone {
    /// Создает новый `OrderZone`.
    /// * `target_order` — целевой порядок гармоники (например, 1.0, 2.0, 0.5 RPM).
    /// * `half_width` — настраиваемая полуширина захвата в долях порядка (например, 0.05).
    ///     - Для жестких условий (стабильные обороты) берут ±0.02 порядка.
    ///     - Для плавающих режимов (пуски/выбеги) ширину увеличивают до ±0.05..±0.1 порядка.
    /// * `n_fft` — размер буфера FFT (например, 8192).
    /// * `n_rev` — количество отсчетов на один оборот вала.
    pub fn new(target_order: f64, half_width: f64, n_fft: usize, n_rev: usize) -> Self {
        let delta_o = n_rev as f64 / n_fft as f64; // Разрешение спектра порядков [1, 2, 3]
        // Находим центральный бин и полуширину в бинах [1, 2, 3]
        let idx_center = (target_order / delta_o).round() as isize;
        let b_half = (half_width / delta_o).ceil() as isize;
        let isize_start = idx_center - b_half;
        let isize_end = idx_center + b_half;
        // Защита от выхода за границы спектра (от 0 до N_fft / 2)
        let idx_start = isize_start.max(0) as usize;
        let idx_end = isize_end.min((n_fft / 2) as isize) as usize;
        let n_bins = idx_end - idx_start + 1;
        // Генерируем веса окна Ханна (полупериод косинуса / колокол) [1, 2]
        let mut window_weights = Vec::with_capacity(n_bins);
        let mut sum_sq_weights = 0.0;
        for m in 0..n_bins {
            let weight = if n_bins > 1 {
                // Классическое окно Ханна, адаптированное под размер зоны [1, 2]
                0.5 * (1.0 - ((2.0 * std::f64::consts::PI * m as f64) / (n_bins - 1) as f64).cos())
            } else {
                1.0
            };
            window_weights.push(weight);
            sum_sq_weights += weight * weight;
        }
        // Защита от деления на ноль, если в зону попал всего 1 бин
        let energy_correction_factor = if sum_sq_weights > 0.0 { sum_sq_weights } else { 1.0 };
        Self {
            amplitude_factor: 2.0.sqrt() / n_fft as f64,
            idx_start,
            n_bins,
            window_weights,
            energy_correction_factor,
        }
    }
    /// Возвращает RMS энергию зоны.
    /// - `orders` - Массив амплитуд спектра FFT (размером N_fft / 2).
    #[inline]
    pub fn integrate<T>(&self, orders: &[Complex<T>]) -> Rms<f64> 
    where 
        T: crate::num_traits::Float + crate::num_traits::FloatConst + crate::num_traits::ToPrimitive {
        let mut weighted_amplitude_sum = 0.0;
        // Проходим только по бинам нашей зоны интереса
        for m in 0..self.n_bins {
            let fft_idx = self.idx_start + m;
            if fft_idx < orders.len() {
                let raw_amplitude = orders[fft_idx].abs().to_f64().unwrap_or(0.0);
                let weight = self.window_weights[m];
                // Взвешиваем амплитуду и накапливаем сумму квадратов [1, 2, 3]
                weighted_amplitude_sum += (raw_amplitude * weight).powi(2);
            }
        }
        // Корректируем потери энергии от наложения окна и извлекаем корень (RMS) [1, 2, 3]
        // amplitude_factor возводится в квадрат, так как weighted_amplitude_sum содержит квадраты амплитуд
        Rms((self.amplitude_factor.powi(2) * weighted_amplitude_sum / self.energy_correction_factor).sqrt())
    }
}
