use std::f64::consts::PI;
///
/// Звено второго порядка (биквад) для независимой фильтрации I/Q каналов.
///
/// Реализует БИХ-фильтр (IIR) 2-го порядка в топологии **Transposed Direct Form II**.
/// Эта форма требуется заданием (шаг 3.3): при полюсах, близких к единичной окружности
/// (узкая полоса `fc ≪ fs`, например 3.5 Гц при 16 кГц), внутренние узлы имеют ограниченный
/// динамический диапазон, и ошибки округления накапливаются меньше, чем в Direct Form II.
///
/// Коэффициенты рассчитываются по формулам RBJ (Audio EQ Cookbook) для ФНЧ 2-го порядка
/// с заданной добротностью `q_factor`. Каскад из двух звеньев с добротностями
/// `0.5412` и `1.3066` даёт фильтр Баттерворта 4-го порядка.
///
/// Структура хранит один набор коэффициентов и изолированные состояния
/// отдельно для каналов I (вещественная часть) и Q (мнимая часть) комплексной огибающей.
/// Состояние каждого канала: два накопителя `s1`, `s2` (не задержанные отсчёты, а частичные суммы).
pub struct Biquad {
    /// Коэффициент числителя b0 передаточной функции H(z).
    b0: f64,
    /// Коэффициент числителя b1.
    b1: f64,
    /// Коэффициент числителя b2.
    b2: f64,
    /// Коэффициент знаменателя a1 (нормирован на a0, в разностном уравнении входит со знаком «минус»).
    a1: f64,
    /// Коэффициент знаменателя a2 (нормирован на a0, в разностном уравнении входит со знаком «минус»).
    a2: f64,
    // --- Состояние канала I (In-phase) ---
    /// Первый накопитель Transposed DF II, канал I.
    s1_i: f64,
    /// Второй накопитель Transposed DF II, канал I.
    s2_i: f64,
    // --- Состояние канала Q (Quadrature) ---
    /// Первый накопитель Transposed DF II, канал Q.
    s1_q: f64,
    /// Второй накопитель Transposed DF II, канал Q.
    s2_q: f64,
}
//
impl Default for Biquad {
    /// Создаёт биквад с нулевыми коэффициентами и нулевым состоянием.
    ///
    /// Такой фильтр на любом входе выдаёт ноль. Для работы используйте [`Biquad::new`].
    fn default() -> Self {
        Self {
            b0: 0.0, b1: 0.0, b2: 0.0,
            a1: 0.0, a2: 0.0,
            s1_i: 0.0, s2_i: 0.0,
            s1_q: 0.0, s2_q: 0.0,
        }
    }
}
//
impl Biquad {
    /// Рассчитывает коэффициенты биквадного ФНЧ 2-го порядка по физическим параметрам.
    ///
    /// Для одиночной секции Баттерворта 2-го порядка `q_factor = 1/√2 ≈ 0.7071`.
    /// Для каскада Баттерворта 4-го порядка секциям нужны разные добротности:
    /// `Q_k = 1 / (2·cos((2k−1)·π/8))`, то есть `0.5412` и `1.3066`.
    ///
    /// # Аргументы
    /// * `f_cutoff` - Частота среза (уровень −3 дБ для одной секции с Q = 1/√2), Гц.
    /// * `f_sample_dec` - Частота дискретизации обрабатываемого сигнала (после децимации), Гц.
    /// * `q_factor` - Добротность секции, определяет форму АЧХ вблизи среза.
    ///
    /// # Алгоритм расчёта коэффициентов
    /// ```text
    /// omega0 = 2π · f_cutoff / f_sample_dec
    /// alpha  = sin(omega0) / (2 · q_factor)
    /// a0     = 1 + alpha
    ///
    /// b0 = ((1 − cos(omega0)) / 2) / a0
    /// b1 = (1 − cos(omega0)) / a0
    /// b2 = b0
    /// a1 = (−2 · cos(omega0)) / a0
    /// a2 = (1 − alpha) / a0
    /// ```
    /// Частота `omega0` берётся напрямую, без предыскажения `tan(ω/2)`. При `fc/fs ≪ 1`
    /// отличие от строгого билинейного преобразования пренебрежимо мало.
    pub fn new(f_cutoff: f64, f_sample: f64, q_factor: f64) -> Self {
        let omega0 = 2.0 * PI * f_cutoff / f_sample;
        let alpha = omega0.sin() / (2.0 * q_factor);
        let cos_omega0 = omega0.cos();

        let a0 = 1.0 + alpha;
        let b0 = ((1.0 - cos_omega0) / 2.0) / a0;
        let b1 = (1.0 - cos_omega0) / a0;
        let b2 = b0;
        let a1 = (-2.0 * cos_omega0) / a0;
        let a2 = (1.0 - alpha) / a0;

        Self {
            b0, b1, b2, a1, a2,
            s1_i: 0.0, s2_i: 0.0,
            s1_q: 0.0, s2_q: 0.0,
        }
    }
    /// Горячий цикл фильтрации одного вещественного отсчёта (Transposed Direct Form II).
    ///
    /// Разностные уравнения:
    /// ```text
    /// y[n]  = b0 · x[n] + s1[n−1]
    /// s1[n] = b1 · x[n] − a1 · y[n] + s2[n−1]
    /// s2[n] = b2 · x[n] − a2 · y[n]
    /// ```
    /// Передаточная функция совпадает с Direct Form II, отличается только структура
    /// вычислений и численные свойства. Стоимость: 5 умножений на отсчёт.
    #[inline]
    fn process_one(b0: f64, b1: f64, b2: f64, a1: f64, a2: f64,
                   x: f64, s1: &mut f64, s2: &mut f64) -> f64 {
        let y = b0 * x + *s1;
        *s1 = b1 * x - a1 * y + *s2;
        *s2 = b2 * x - a2 * y;
        y
    }
    /// Выполняет синхронную фильтрацию комплексного I/Q отсчёта.
    ///
    /// Вещественная (`i`) и мнимая (`q`) составляющие проходят через один и тот же набор
    /// коэффициентов, но с независимым состоянием. Состояние сохраняется между вызовами,
    /// поэтому пакеты данных можно подавать подряд без разрывов на стыках.
    ///
    /// # Аргументы
    /// * `i` - Текущий отсчёт канала I (In-phase).
    /// * `q` - Текущий отсчёт канала Q (Quadrature).
    ///
    /// # Возвращает
    /// Кортеж `(I_out, Q_out)` — отфильтрованный комплексный отсчёт.
    #[inline]
    pub fn process(&mut self, i: f64, q: f64) -> (f64, f64) {
        let y_i = Self::process_one(self.b0, self.b1, self.b2, self.a1, self.a2, i, &mut self.s1_i, &mut self.s2_i);
        let y_q = Self::process_one(self.b0, self.b1, self.b2, self.a1, self.a2, q, &mut self.s1_q, &mut self.s2_q);
        (y_i, y_q)
    }
}