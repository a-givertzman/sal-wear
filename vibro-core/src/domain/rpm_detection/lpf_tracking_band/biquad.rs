use std::f64::consts::PI;
///
/// Звено второго порядка (Биквад) для независимой фильтрации I/Q каналов.
///
/// Реализует цифровой КИХ/ИИХ фильтр (IIR) второго порядка на базе Прямой Формы II.
/// Коэффициенты рассчитываются с помощью билинейного Z-преобразования для аналогового прототипа 
/// низкочастотного фильтра Баттерворта.
/// 
/// Структура хранит единый набор коэффициентов фильтрации и изолированные внутренние состояния 
/// (линии задержки) отдельно для вещественной (I) и мнимой (Q) компонент комплексного огибающего сигнала.
pub struct Biquad {
    /// Коэффициент числителя b0 передаточной функции H(z)
    b0: f64,
    /// Коэффициент числителя b1 передаточной функции H(z)
    b1: f64,
    /// Коэффициент числителя b2 передаточной функции H(z)
    b2: f64,
    /// Коэффициент знаменателя a1 передаточной функции H(z) (знак инвертирован для разностного уравнения)
    a1: f64,
    /// Коэффициент знаменателя a2 передаточной функции H(z) (знак инвертирован для разностного уравнения)
    a2: f64,
    // --- Линия задержки вещественного канала (In-phase, I) ---
    /// Промежуточное состояние первого порядка w[n-1] для канала I
    w1_i: f64,
    /// Промежуточное состояние второго порядка w[n-2] для канала I
    w2_i: f64,
    // --- Линия задержки мнимого канала (Quadrature, Q) ---
    /// Промежуточное состояние первого порядка w[n-1] для канала Q
    w1_q: f64,
    /// Промежуточное состояние второго порядка w[n-2] для канала Q
    w2_q: f64,
}
//
impl Default for Biquad {
    /// Создает пустой биквад с нулевыми коэффициентами и чистой линией задержки.
    fn default() -> Self {
        Self { 
            b0: 0.0, b1: 0.0, b2: 0.0, 
            a1: 0.0, a2: 0.0, 
            w1_i: 0.0, w2_i: 0.0, 
            w1_q: 0.0, w2_q: 0.0 
        }
    }
}
//
impl Biquad {
    /// Рассчитывает коэффициенты цифрового биквадратного ФНЧ Баттерворта по физическим параметрам.
    ///
    /// Математический синтез основан на частотно-преобразованном прототипе Баттерворта 2-го порядка 
    /// с нормировкой добротности `q_factor`. Для классического гладкого фильтра Баттерворта 
    /// значение добротности должно составлять Q = 1 / sqrt(2), что примерно равно 0.7071.
    ///
    /// # Аргументы
    /// * `f_cutoff` - Частота среза фильтра (Fc), Гц (граница полосы слежения)
    /// * `f_sample` - Рабочая частота дискретизации сигнала, Гц (для конвейера — 16 000 Гц)
    /// * `q_factor` - Добротность фильтра (Q), определяющая форму спада АЧХ и ФЧХ
    ///
    /// # Алгоритм расчета коэффициентов:
    ///   omega0 = 2.0 * PI * f_cutoff / f_sample
    ///   alpha  = sin(omega0) / (2.0 * q_factor)
    ///   a0     = 1.0 + alpha
    /// 
    ///   b0 = ((1.0 - cos(omega0)) / 2.0) / a0
    ///   b1 = (1.0 - cos(omega0)) / a0
    ///   b2 = b0
    ///   a1 = (-2.0 * cos(omega0)) / a0
    ///   a2 = (1.0 - alpha) / a0
    pub fn new(f_cutoff: f64, f_sample: f64, q_factor: f64) -> Self {
        let omega0 = 2.0 * PI * f_cutoff / f_sample;
        let alpha = omega0.sin() / (2.0 * q_factor);
        let cos_omega0 = omega0.cos();

        let a0 = 1.0 + alpha;
        let b0 = ((1.0 - cos_omega0) / 2.0) / a0;
        let b1 = (1.0 - cos_omega0) / a0;
        let b2 = b0;
        let a1 = (-2.0 * cos_omega0) / a0;
        let a2 = (1.0 - alpha) / a0;

        Self { 
            b0, b1, b2, a1, a2, 
            w1_i: 0.0, w2_i: 0.0, 
            w1_q: 0.0, w2_q: 0.0 
        }
    }
    /// Внутренний горячий цикл фильтрации одного вещественного отсчета (Прямая Форма II).
    ///
    /// Реализует разностное уравнение ИИХ-фильтра 2-го порядка через промежуточное состояние w[n]:
    ///   w[n] = x[n] - a1 * w[n-1] - a2 * w[n-2]
    ///   y[n] = b0 * w[n] + b1 * w[n-1] + b2 * w[n-2]
    /// 
    #[inline]
    fn process_one(b0: f64, b1: f64, b2: f64, a1: f64, a2: f64, x: f64, w1: &mut f64, w2: &mut f64) -> f64 {
        let w = x - a1 * (*w1) - a2 * (*w2);
        let y = b0 * w + b1 * (*w1) + b2 * (*w2);
        *w2 = *w1;
        *w1 = w;
        y
    }
    /// Выполняет синхронную фильтрацию комплексного I/Q отсчета сигнала.
    ///
    /// Пропускает вещественную (i) и мнимую (q) составляющие вектора через один и тот же математический 
    /// базис фильтра, но с независимым сохранением предыстории в соответствующих внутренних регистрах задержки.
    ///
    /// # Аргументы
    /// * `i` - Текущий вещественный отсчет комплексного сигнала (In-phase компонента)
    /// * `q` - Текущий мнимый отсчет комплексного сигнала (Quadrature компонента)
    ///
    /// # Возвращаемое значение
    /// Кортеж `(f64, f64)`, представляющий собой отфильтрованный комплексный отсчет `(I_out, Q_out)`.
    pub fn process(&mut self, i: f64, q: f64) -> (f64, f64) {
        let y_i = Self::process_one(self.b0, self.b1, self.b2, self.a1, self.a2, i, &mut self.w1_i, &mut self.w2_i);
        let y_q = Self::process_one(self.b0, self.b1, self.b2, self.a1, self.a2, q, &mut self.w1_q, &mut self.w2_q);
        (y_i, y_q)
    }
}
