/// Модульные тесты для проверки корректности алгоритма децимации и антиалиасинг-фильтрации.
#[cfg(test)]
mod tests {
    use chrono::Utc;
use sal_core::dbg::Dbg;
    use crate::{AngularCtx, Decimation, Eval, Frame, tests::{Frequency, Udp}};
    /// Фиктивный конечный дочерний элемент (`DummyChild`) для изоляции тестируемого блока.
    /// 
    /// Реализует типаж `Eval`. Не выполняет никаких модификаций контекста и не вносит 
    /// собственные ошибки, позволяя тестировать дециматор в чистом виде (как изолированный узел цепочки).
    struct DummyChild;
    impl Eval<AngularCtx, AngularCtx> for DummyChild {
        /// Просто возвращает входящий контекст без изменений, завершая цепочку вызовов.
        fn eval(&self, ctx: AngularCtx) -> AngularCtx { ctx }
        /// Сигнализирует о корректном выходе из вычислительного узла.
        fn exit(&self) {}
    }
    /// Тест проверки коэффициента децимации и результирующей длины выходного буфера отсчетов.
    ///
    /// # Цель теста
    /// Убедиться, что при прореживании непрерывного потока данных с плавающей фазой 
    /// сохраняется корректное количество выходных сэмплов, вычисленное как `N_in / M`.
    /// 
    /// # Физическая суть
    /// На вход подается чанк размером 512 отсчетов. При базовом коэффициенте децимации `M = 20` 
    /// математическое ожидание длины составляет `512 / 20 = 25.6`. Поскольку 512 не делится нацело 
    /// на 20, счетчик фазы прореживания (`dec_counter`) переносится между пакетами, поэтому 
    /// длина выходного вектора в зависимости от накопленной фазы обязана строго находиться в диапазоне от 25 до 26 сэмплов.
    #[test]
    fn test_decimation_factor_and_length() {
        let dbg = Dbg::own("test_decimation_factor_and_length");
        let conf_adc_sample_rate_hz = 320000.0;
        let conf_adc_chunk_size = 512;
        let decimator = Decimation::new(&dbg, DummyChild);
        // Формируем чистую "тишину" на нулевом уровне (без гармоник), чтобы проверить исключительно геометрию буферов
        let mut udp = Udp::new(512, 320_000.0, []);
        let mut samples = [0u16; 512];
        udp.parse(0.0, &mut samples); // Значение RPM не важно, так как гармоники отсутствуют
        let mut ctx = AngularCtx::new(conf_adc_sample_rate_hz, conf_adc_chunk_size);
        let ts = Utc::now();
        let frame = Frame::raw(ts, 2048.0, &samples);
        ctx.push_chunk(&frame);
        // Выполняем децимацию сигнала
        let result_ctx = decimator.eval(ctx);
        // Проверка: размер выходного буфера должен соответствовать математическому расчету с учетом дробного сдвига фазы
        assert!(
            result_ctx.rpm_detection.decimation.decimated.len() >= 25 && result_ctx.rpm_detection.decimation.decimated.len() <= 26,
            "Неожиданное количество децимированных сэмплов: {}",
            result_ctx.rpm_detection.decimation.decimated.len()
        );
        // Гарантируем, что внутри конвейера не возникло непредвиденных вычислительных или логических ошибок
        assert!(!result_ctx.err.is_some());
    }
    /// Тест эффективности антиалиасинг-фильтрации (подавления частот выше частоты Найквиста).
    ///
    /// # Цель теста
    /// Проверить способность КИХ-фильтра эффективно ослаблять компоненты спектра, лежащие 
    /// за пределами новой частоты Найквиста (`f_decimation / 2 = 8 кГц`), предотвращая их зеркальное 
    /// наложение (aliasing) в область низких частот.
    /// 
    /// # Физическая суть
    /// Генерируется сложный сигнал, состоящий из:
    /// 1. Полезного низкочастотного сигнала на частоте `50 Гц` с амплитудой `500`.
    /// 2. Мощной высокочастотной помехи на частоте `40 000 Гц` (40 кГц) с удвоенной амплитудой `1000`.
    /// 
    /// Поскольку частота 40 кГц значительно выше частоты среза ФНЧ (8 кГц), после прохождения КИХ-фильтра 
    /// амплитуда помехи должна упасть практически до нуля. Общая амплитуда отсчетов не должна 
    /// превышать уровень полезного сигнала с учетом переходных процессов (порог 1.5 * Амплитуда_полезная).
    #[test]
    fn test_anti_aliasing_filtering() {
        let dbg = Dbg::own("test_anti_aliasing_filtering");
        let conf_adc_sample_rate_hz = 320000.0;
        let conf_adc_chunk_size = 512;
        let decimator = Decimation::new(&dbg, DummyChild);
        let fs = 320_000.0;
        // Инициализируем генератор сигнала: 50Гц (А=500) + Шум 40кГц (А=1000)
        let mut udp = Udp::new(
            512,
            fs,
            [
                (Frequency::Static(50.0), 500),
                (Frequency::Static(40_000.0), 1000),
            ],
        );
        let mut ctx = AngularCtx::new(conf_adc_sample_rate_hz, conf_adc_chunk_size);
        let mut all_decimated: Vec<f64> = Vec::new();
        // Симулируем потоковую обработку двух последовательных чанков для заполнения линии задержки фильтра
        for _ in 0..2 {
            let mut samples = [0u16; 512];
            udp.parse(0.0, &mut samples); // RPM не важен, так как обе компоненты частоты заданы жестко (Static)
            let ts = Utc::now();
            let frame = Frame::raw(ts, 2048.0, &samples);
            ctx.push_chunk(&frame);
            ctx = decimator.eval(ctx);
            all_decimated.extend(&ctx.rpm_detection.decimation.decimated);
        }
        // Выполняем спектральную валидацию: проверяем, что ВЧ-помеха успешно подавлена КИХ-фильтром.
        // Порог масштабирован под реальное физическое значение амплитуды А=500, а не под абстрактный диапазон [-1.0, 1.0].
        for &sample in &all_decimated {
            assert!(
                sample.abs() < 1.5 * 500.0,
                "Фильтр не подавил высокочастотный шум! Значение: {sample}"
            );
        }
        // Проверяем отсутствие ошибок выполнения конвейера данных
        assert!(!ctx.err.is_some());
    }
}
