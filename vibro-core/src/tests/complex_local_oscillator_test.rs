    /// Тест математической корректности сдвига спектра комплексным гетеродином.
    ///
    /// # Цель теста
    /// Проверить, что умножение вещественного сигнала на комплексную экспоненту гетеродина 
    /// `e^(-j * 2*pi * f_hat * t)` осуществляет строго линейный перенос (сдвиг) всего спектра 
    /// влево во во временной области без искажения амплитуд.
    /// 
    /// # Физико-математическое обоснование
    /// Вещественный гармонический сигнал частоты `f_1X = 50 Гц` с амплитудой `A = 2.0` математически 
    /// состоит из двух комплексных сопряженных экспонент с амплитудами `A/2 = 1.0` на частотах `+50 Гц` и `-50 Гц`.
    /// 
    /// При настройке гетеродина на грубую частоту `f_hat = 49 Гц` происходит перенос спектра на `-49 Гц`:
    /// 1. Компонента `+50 Гц` переходит на разностную частоту: `50 - 49 = +1 Гц` (целевой бин около нуля).
    /// 2. Компонента `-50 Гц` переходит на суммарную частоту: `-50 - 49 = -99 Гц`.
    /// 
    /// Тест выполняет однобиновое ДФТ (`dft_bin`) на ключевых частотах, проверяя точное распределение энергии.
    #[test]
    fn test_1x_shifted_to_dc() {
        let (fs, a) = (16_000.0, 2.0);
        // Генерируем 1 секунду чистого вещественного косинуса 50 Гц с амплитудой 2.0
        let x: Vec<f64> = (0..16_000)
            .map(|n| a * (2.0 * PI * 50.0 * n as f64 / fs).cos())
            .collect();
        // Запускаем узел конвейера. Передаем частоту гетеродина 49 Гц (переведенную в об/мин: 49 * 60)
        let ctx = node().eval(ctx_with(x, fs, 49.0 * 60.0));
        let y = &ctx.rpm_detection.complex_local_oscillator.complex_signal;
        // Геометрическая проверка: количество комплексных отсчетов должно совпадать с входными
        assert_eq!(y.len(), 16_000);
        // Вычисляем амплитуды на ожидаемых частотах после переноса спектра
        let diff = dft_bin(y, 1.0, fs).norm();   // Разностная частота (+1 Гц)
        let sum = dft_bin(y, -99.0, fs).norm(); // Суммарная зеркальная частота (-99 Гц)
        // 1. Проверяем разностную частоту: энергия +50 Гц должна плавно сместиться в +1 Гц с амплитудой A/2 = 1.0
        assert!((diff - a / 2.0).abs() < 1e-6, "разностная: {diff}, ожидалось {}", a / 2.0);
        // 2. Проверяем суммарную частоту: зеркальная компонента -50 Гц должна уйти в -99 Гц с амплитудой A/2 = 1.0
        assert!((sum - a / 2.0).abs() < 1e-6, "суммарная: {sum}, ожидалось {}", a / 2.0);
        // 3. Убеждаемся, что исходная частота полностью очищена (спектр гарантированно сдвинулся)
        assert!(dft_bin(y, 50.0, fs).norm() < 1e-6, "компонента осталась на 50 Гц: сдвига нет");
        // 4. Проверяем знак сдвига: на частоте +99 Гц энергии быть не должно (подтверждает умножение на e^-j, а не e^+j)
        assert!(dft_bin(y, 99.0, fs).norm() < 1e-6, "зеркальный знак: частота ушла не туда");
    }
    /// Проверка соглашения о знаках комплексной экспоненты гетеродина `e^(-jφ)`.
    ///
    /// # Цель теста
    /// Математически верифицировать правильность знака мнимой части при формировании 
    /// комплексного поворачивающего множителя. Тест гарантирует, что конвейер использует 
    /// сопряженную экспоненту `e^(-jφ) = cos(φ) - j*sin(φ)`, обеспечивающую вращение 
    /// вектора по часовой стрелке.
    /// 
    /// # Физико-математическое обоснование
    /// На вход подается константный сигнал `x[n] = 1.0`. Проверяются две критические точки:
    /// 1. При начальной фазе `φ = 0` комплексная экспонента `e^(-j*0) = 1 + 0j`. 
    ///    Мнимая часть выходного сигнала обязана быть строго нулевой.
    /// 2. При шаге фазы `φ = π/2` комплексная экспонента `e^(-j*π/2) = 0 - 1j`. 
    ///    Мнимая часть выходного сигнала обязана быть строго отрицательной (равной `-1.0`).
    /// 
    /// В случае ошибки знака (использование `e^(+jφ)`) вектор на фазе `π/2` примет значение `0 + 1j`, 
    /// что приведет к положительной мнимой части и вызовет падение утверждения `assert!`.
    #[test]
    fn test_sign_convention() {
        let fs = 16_000.0;
        let n = node();
        // --- Точка 1: Фаза φ = 0 (raw_rpm = 0 Гц) ---
        let ctx_zero = n.eval(ctx_with(vec![1.0; 1], fs, 0.0));
        let y_zero = &ctx_zero.rpm_detection.complex_local_oscillator.complex_signal[0];
        assert!((y_zero.re - 1.0).abs() < 1e-12, "При φ=0 вещественная часть должна быть 1.0");
        assert!(y_zero.im.abs() < 1e-12, "При φ=0 мнимая часть должна быть строго 0.0");
        // --- Точка 2: Фаза φ = π/2 (Гетеродин настроен на четверть частоты дискретизации) ---
        // Шаг фазы на один сэмпл составит: 2*pi * (fs/4) / fs = pi/2
        let ctx_quad = n.eval(ctx_with(vec![1.0; 2], fs, (fs / 4.0) * 60.0));
        let y_quad = &ctx_quad.rpm_detection.complex_local_oscillator.complex_signal;
        // Отсчет n=0 (φ = 0)
        assert!((y_quad[0].re - 1.0).abs() < 1e-12);
        assert!(y_quad[0].im.abs() < 1e-12);
        // Отсчет n=1 (φ = π/2). Ожидаем e^(-j*pi/2) = 0 - 1j
        assert!(
            y_quad[1].im < 0.0, 
            "Ошибка знака экспоненты! Мнимая часть должна быть отрицательной, получено: {}", 
            y_quad[1].im
        );
        assert!((y_quad[1].re - 0.0).abs() < 1e-12, "Вещественная часть на φ=π/2 должна быть 0.0"); //cos(pi/2)
        assert!((y_quad[1].im - (-1.0)).abs() < 1e-12, "Мнимая часть на φ=π/2 должна быть строго -1.0"); // sin(pi/2)
    }
    /// Тест непрерывности накопления фазы гетеродина на стыке чанков с изменяющейся частотой.
    ///
    /// # Цель теста
    /// Математически доказать, что фаза локального осциллятора рассчитывается как интеграл скорости 
    /// (накапливаемая величина), а не как прямое произведение мгновенной частоты на абсолютное время `f_hat * t`. 
    /// Тест гарантирует отсутствие фазовых разрывов (скачков первого рода) при динамическом изменении RPM.
    /// 
    /// # Физико-математическое обоснование
    /// Процесс симулирует потоковую обработку двух последовательных пакетов по `n = 13` отсчетов:
    /// 1. В первом пакете частота вала составляет `f_1 = 50 Гц`. Фаза интегрируется от `0` до конечного 
    ///    значения `phi_last` со скоростью приращения `delta_phi_1 = 2*pi*50/fs`.
    /// 2. Во втором пакете частота скачкообразно меняется до `f_2 = 60 Гц`. 
    /// 
    /// При физически корректной реализации начальная фаза второго пакета (`phi_net[0]`) должна строго 
    /// совпасть с конечной фазой первого пакета (`phi_last`), обеспечивая гладкость функции. 
    /// В случае ошибочной реализации через `f_hat * t` на стыке пакетов возникнет мгновенный скачок фазы 
    /// на величину `13 * 2*pi*(60 - 50)/fs`, что приведет к спектральному взрыву и разрыву трекинга вала.
    #[test]
    fn test_phase_accumulation_continuity() {
        let fs = 16_000.0;
        let n_samples = 13usize;
        let n = node();
        // --- ПАКЕТ 1: Обработка на частоте 50 Гц ---
        let ctx = n.eval(ctx_with(vec![1.0; n_samples], fs, 50.0 * 60.0));
        let phi_end_1 = ctx.rpm_detection.complex_local_oscillator.phi_last;
        // Аналитически рассчитываем, где должна закончиться фаза после 13 сэмплов на 50 Гц
        let expected_end_1 = (n_samples as f64 * 2.0 * PI * 50.0 / fs).rem_euclid(2.0 * PI);
        // Проверяем, что первый пакет рассчитался математически верно
        assert!(wrap(phi_end_1 - expected_end_1).abs() < 1e-12, "phi_last после пакета 1 = {phi_end_1}");
        // --- ПАКЕТ 2: Скачкообразный переход на частоту 60 Гц ---
        let mut ctx = ctx;
        ctx.raw_rpm = 60.0 * 60.0; // Симулируем мгновенное ускорение генератора/двигателя
        ctx.rpm_detection.decimation.decimated = vec![1.0; n_samples];
        // Прогоняем второй пакет через гетеродин
        let ctx = n.eval(ctx);
        let phi = &ctx.rpm_detection.complex_local_oscillator.phi_net;
        // 1. ПРОВЕРКА ИНВАРИАНТА НЕПРЕРЫВНОСТИ: 
        // Начальная фаза нового пакета обязана быть бесшовным продолжением предыдущего
        assert!(
            wrap(phi[0] - phi_end_1).abs() < 1e-12, 
            "Обнаружен скачок фазы на стыке чанков: {} vs {phi_end_1}", 
            phi[0]
        );
        // 2. ПРОВЕРКА ДИНАМИКИ ШАГА: 
        // Убеждаемся, что приращение фазы внутри второго пакета пошло уже по новой частоте (60 Гц)
        let expected_step_2 = 2.0 * PI * 60.0 / fs;
        assert!(
            wrap(phi[1] - phi[0] - expected_step_2).abs() < 1e-12, 
            "Внутри второго чанка шаг фазы не соответствует новой частоте 60 Гц"
        );
        // 3. ПРОВЕРКА ОТ ПРОТИВНОГО (Защита от архитектурной ошибки f_hat * t):
        // Рассчитываем ложную фазу, которая получилась бы, если бы мы просто подставили 60 Гц в формулу f_hat * t
        let wrong_static_phase = (n_samples as f64 * 2.0 * PI * 60.0 / fs).rem_euclid(2.0 * PI);
        assert!(
            wrap(phi[0] - wrong_static_phase).abs() > 1e-3, 
            "Критический дефект: фаза совпала со статической моделью f_hat * t. Интегрирование скорости разрушено!"
        );
    }
