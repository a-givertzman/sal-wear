    /// ctx с готовым `decimated`, минуя Decimation.
    fn ctx_with(decimated: Vec<f64>, f_sample_dec: f64, raw_rpm: f64) -> AngularCtx {
        let mut ctx = AngularCtx::default();
        ctx.raw_rpm = raw_rpm;
        ctx.rpm_detection.decimation.decimated = decimated;
        ctx.rpm_detection.decimation.f_sample_dec = f_sample_dec;
        ctx
    }
    /// Однобиновое ДФТ комплексного сигнала на частоте `f` Гц: (1/N)·Σ y[n]·e^(-j2πfn/fs).
    /// При целом числе периодов в окне бины ортогональны, утечки нет.
    fn dft_bin(y: &[Complex<f64>], f: f64, fs: f64) -> Complex<f64> {
        let mut acc = Complex::new(0.0, 0.0); // 1. Инициализируем комплексный аккумулятор (векторный сумматор)
        for (n, v) in y.iter().enumerate() {  // 2. Идем по всем отсчетам сигнала. n — индекс времени, v — значение сэмпла
            // 3. Вычисляем мгновенную фазу опорного синуса для текущего шага времени n
            let a = -2.0 * PI * f * n as f64 / fs;
            // 4. Умножаем отсчет сигнала на комплексный синус/косинус и добавляем в аккумулятор.
            // Это эквивалентно: v * (cos(a) + j*sin(a))
            acc += *v * Complex::new(a.cos(), a.sin());
        }
        // 5. Делим сумму на количество элементов, чтобы получить нормированную амплитуду
        acc / y.len() as f64
    }
    /// Разность углов, приведённая к (-π, π].
    fn wrap(d: f64) -> f64 { (d + PI).rem_euclid(2.0 * PI) - PI }
