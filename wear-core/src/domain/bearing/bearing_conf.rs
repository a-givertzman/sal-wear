#[derive(Debug, Clone, PartialEq)]
/// Входные данные для расчёта
/// накопленного повреждения подшипника
/// # Поля
/// * `p_motor` — мощность двигателя
/// * `n_motor` — частота вращения двигателя
/// * `d_motor` — диаметр вала двигателя
/// * `x` — коэффициент радиальной нагрузки для расчёта эквивалентной нагрузки
/// * `y` — коэффициент осевой нагрузки для расчёта эквивалентной нагрузки
/// * `cr` — динамическая грузоподъёмность подшипника
/// * `p` — показатель степени кривой усталости
/// * `q10` — коэффициент ускорения износа на +10°C
/// * `rpm` — скорость вращения вала в оборотах в минуту
/// * `duration` — длительность устойчивого режима
/// * `t_temp` — температура подшипникового узла
/// * `t_ref` — опорная (номинальная рабочая) температура подшипника
/// ```yaml
/// service WearCore BearingWearCore
///    
///    p_motor: 15.0       # Мощность двигателя, кВт
///    n_motor: 1500.0     # Номинальная частота вращения двигателя, об/мин
///    d_motor: 45.0       # Диаметр вала двигателя, мм
///    
///    x: 0.56             # Коэффициент радиальной нагрузки
///    y: 1.45             # Коэффициент осевой нагрузки
///    cr: 32.5            # Динамическая грузоподъёмность подшипника, кН
///    
///    p: 3.0              # Показатель степени кривой усталости (3.0 для шариковых, 3.33 для роликовых)
///    q10: 2.0            # Коэффициент ускорения износа на каждые +10°C (правило Вант-Гоффа)
///    
///    rpm: 1480.0         # Текущая скорость вращения вала, об/мин (в коде опечатка rmp вместо rpm)
///    duration: 120.0     # Длительность устойчивого режима, минут
///    
///    t_temp: 75.0        # Текущая температура подшипникового узла, °C
///    t_ref: 50.0         # Опорная (номинальная рабочая) температура подшипника, °C
/// ```
pub struct BearingConf {
    pub p_motor: f64,
    pub n_motor: f64,
    pub d_motor: f64,
    pub x: f64,
    pub y: f64,
    pub cr: f64,
    pub p: f64,
    pub q10: f64,
    pub rpm: f64,
    pub duration: f64,
    pub t_temp: f64,
    pub t_ref: f64,
}
//
impl BearingConf {
    /// Новый экземпляр [BearingConf]
    pub fn new(
        p_motor: f64,
        n_motor: f64,
        d_motor: f64,
        x: f64,
        y: f64,
        cr: f64,
        p: f64,
        q10: f64,
        rpm: f64,
        duration: f64,
        t_temp: f64,
        t_ref: f64,
    ) -> Self {
        Self {
            p_motor,
            n_motor,
            d_motor,
            x,
            y,
            cr,
            p,
            q10,
            rpm,
            duration,
            t_temp,
            t_ref,
        }
    }
}